//! # Format version 2 (M1): every new field round-trips; format 1 upgrades
//!
//! ## What this file checks
//! - New files have the **current format version** (2 in M1, 3 since
//!   blockers, D23); the tests use `CURRENT_FORMAT_VERSION`, not a literal.
//! - Every field the model got in M1 survives save → open unchanged: task
//!   mode and manual start, milestone flag, all eight constraints, deadline,
//!   task calendar, notes, hyperlink, the project's schedule-from and finish
//!   date, percentage lags, and calendar exceptions (working and
//!   non-working, **in their order**, because the first one wins on overlap).
//! - A **format-1 file** (written by M0) is upgraded when opened:
//!   `upgraded_from == Some(1)`, non-working rows become holidays, working
//!   rows become exceptions, and the old derived `is_milestone` flag is
//!   reset (a zero-duration task is still a milestone by its duration).
//!
//! ## Where it fits
//! Part of the `gtra` test target (`tests/rust/gtra/main.rs`).
//!
//! ## Main ideas
//! The format-1 file is **generated by a helper** ([`write_format_1_file`]):
//! we save a normal file, then use plain SQL to turn it back into what M0
//! wrote (drop the two columns added by migration 0002, set the M0 values,
//! stamp version 1). So no binary fixture has to be stored or hand-edited.

use crate::{normalized, open_ok, options, path_in, save_ok, temp_dir};
use ganttora_tests::{date, dt, link, row_id, shed};
use gtra::schema::CURRENT_FORMAT_VERSION;
use gtra::{Compatibility, ProjectSession};
use model::{
    Calendar, CalendarException, Constraint, Dependency, DependencyType, Duration, Project,
    ScheduleFrom, TaskMode, WorkWeek, WorkingTime,
};
use rusqlite::Connection;
use std::path::Path;

/// The shed with every M1 field set to a non-default value somewhere.
///
/// # Returns
/// A project that uses all eight constraints, a deadline, a task calendar,
/// notes, a hyperlink, a manual task, a milestone flag, schedule-from-finish,
/// SS/FF/SF links with time and percentage lags, and a second calendar with
/// overlapping exceptions.
pub(crate) fn every_m1_field() -> Project {
    let mut project = shed();
    project.schedule_from = ScheduleFrom::Finish;
    project.finish = Some(dt("2027-04-30 17:00"));

    let mut crew = Calendar::new("Crew", WorkWeek::standard());
    crew.holidays.insert(date("2027-03-03"));
    crew.holidays.insert(date("2027-03-04"));
    crew.exceptions = vec![
        CalendarException::working(
            "Catch-up Saturday",
            date("2027-03-06"),
            date("2027-03-06"),
            vec![WorkingTime::hours(8, 12), WorkingTime::hours(13, 15)],
        ),
        // Overlaps the Saturday above; it comes second, so it loses.
        CalendarException::non_working("Shutdown", date("2027-03-06"), date("2027-03-12")),
        CalendarException::non_working("Single day", date("2027-03-20"), date("2027-03-20")),
    ];
    let crew_id = crew.id;
    project.calendars.push(crew);

    let constraints = [
        Constraint::AsSoonAsPossible,
        Constraint::AsLateAsPossible,
        Constraint::StartNoEarlierThan {
            date: dt("2027-03-02 08:00"),
        },
        Constraint::StartNoLaterThan {
            date: dt("2027-03-20 08:00"),
        },
        Constraint::FinishNoEarlierThan {
            date: dt("2027-03-10 17:00"),
        },
        Constraint::FinishNoLaterThan {
            date: dt("2027-03-25 17:00"),
        },
        Constraint::MustStartOn {
            date: dt("2027-03-16 08:00"),
        },
        Constraint::MustFinishOn {
            date: dt("2027-03-23 17:00"),
        },
    ];
    for (task, constraint) in project.tasks.iter_mut().zip(constraints) {
        task.constraint = constraint;
    }
    let first = &mut project.tasks[0];
    first.notes = "Ask the neighbours first.\nSecond line «ü»".into();
    first.hyperlink = "https://example.com/plan.pdf".into();
    first.deadline = Some(dt("2027-03-05 17:00"));
    project.tasks[2].calendar_id = Some(crew_id);
    project.tasks[3].mode = TaskMode::Manual;
    project.tasks[3].manual_start = Some(dt("2027-03-06 10:00"));
    project.tasks[4].milestone = true;

    let one = row_id(&project, 1);
    let three = row_id(&project, 3);
    let six = row_id(&project, 6);
    let eight = row_id(&project, 8);
    project
        .dependencies
        .push(Dependency::new(one, six, DependencyType::StartToStart).with_lag_percent(-25));
    project.dependencies.push(
        Dependency::new(three, eight, DependencyType::FinishToFinish)
            .with_lag(Duration::from_hours(-3)),
    );
    project
        .dependencies
        .push(Dependency::new(one, eight, DependencyType::StartToFinish).with_lag_percent(150));
    project
}

/// A newly saved file has the current format version and reports no
/// upgrade.
///
/// Why it matters: M1 added migration 0002 and blockers added 0003; files
/// written now must carry the newest number so older apps open them
/// read-only. We compare with the constant, so the test does not need to be
/// edited each time a new migration is added.
#[test]
fn new_files_have_format_version_2() {
    // Checked while compiling (a `const` assertion): M1 needs format 2 or later.
    const _: () = assert!(CURRENT_FORMAT_VERSION >= 2);
    let dir = temp_dir();
    let path = path_in(&dir, "shed.gtra");
    save_ok(&path, &shed());
    let opened = open_ok(&path);
    assert_eq!(opened.format_version, CURRENT_FORMAT_VERSION);
    assert_eq!(opened.upgraded_from, None);
    assert_eq!(opened.read_only_reason, None);
}

/// Every M1 field survives save → open, with exceptions in their order.
///
/// Why it matters: a field that is not saved is lost the moment the user
/// closes the file. The exception order matters because "the first one
/// wins" when they overlap.
#[test]
fn every_m1_field_round_trips() {
    let project = every_m1_field();
    let dir = temp_dir();
    let path = path_in(&dir, "full.gtra");
    save_ok(&path, &project);
    let opened = open_ok(&path);
    assert!(opened.notes.is_empty(), "notes: {:?}", opened.notes);
    assert_eq!(normalized(&opened.project), normalized(&project));
    let crew = opened
        .project
        .calendars
        .iter()
        .find(|c| c.name == "Crew")
        .expect("crew calendar");
    let names: Vec<&str> = crew.exceptions.iter().map(|e| e.name.as_str()).collect();
    assert_eq!(names, vec!["Catch-up Saturday", "Shutdown", "Single day"]);
}

/// Reversing the exception order and saving again gives the reversed order
/// back.
///
/// Why it matters: the order is data, not an accident of how rows are
/// stored.
#[test]
fn exception_order_is_kept_both_ways() {
    let mut project = every_m1_field();
    project.calendars[1].exceptions.reverse();
    let dir = temp_dir();
    let path = path_in(&dir, "reversed.gtra");
    save_ok(&path, &project);
    let opened = open_ok(&path);
    assert_eq!(normalized(&opened.project), normalized(&project));
}

/// The file's `tasks` table stores the outline as `parent_id` + `position`
/// derived from the row order and levels (M1 Lead decision): with Paint
/// indented under "Build walls and roof", Paint's parent column is that task.
///
/// Why it matters: other tools (and future versions) read the tree from
/// these columns.
#[test]
fn outline_is_written_as_parent_and_position() {
    let mut project = shed();
    project.tasks[6].outline_level = 2;
    let walls = row_id(&project, 6);
    let paint = row_id(&project, 7);
    let dir = temp_dir();
    let path = path_in(&dir, "outline.gtra");
    save_ok(&path, &project);
    let conn = Connection::open(&path).expect("open");
    let parent: Option<String> = conn
        .query_row(
            "SELECT parent_id FROM tasks WHERE id = ?1",
            [paint.to_string()],
            |row| row.get(0),
        )
        .expect("paint row");
    assert_eq!(parent, Some(walls.to_string()));
    drop(conn);
    assert_eq!(open_ok(&path).project, project);
}

/// Writes a format-1 (M0) version of a project to `path`.
///
/// # What it does
/// 1. Saves the project normally (format 2).
/// 2. Opens the file with plain SQLite and undoes migrations 0003 and 0002:
///    drops the `blockers` table (added by 0003), drops the
///    `kind` and `position` columns, adds one *working* exception row (M0
///    files could contain such rows from other tools, but the M0 model
///    ignored them), sets `is_milestone = 1` on zero-duration tasks (M0
///    derived it from the duration), and stamps version 1.
///
/// # Parameters
/// - `path`: where to write the file.
/// - `project`: the project; it should have a holiday on its project
///   calendar so the upgrade has something to sort.
///
/// # Beginner note
/// This "fixture generator" replaces a stored binary test file. Generating
/// the old file from code keeps it readable and easy to change.
pub(crate) fn write_format_1_file(path: &Path, project: &Project) {
    save_ok(path, project);
    let conn = Connection::open(path).expect("open as SQLite");
    conn.execute_batch(
        "PRAGMA foreign_keys = OFF;
         ALTER TABLE tasks DROP COLUMN planned_finish;
         ALTER TABLE tasks DROP COLUMN actual_finish;
         ALTER TABLE tasks DROP COLUMN percent_complete;
         ALTER TABLE tasks DROP COLUMN is_project;
         DROP TABLE risks;
         DROP TABLE blockers;
         ALTER TABLE calendar_exceptions DROP COLUMN kind;
         ALTER TABLE calendar_exceptions DROP COLUMN position;
         UPDATE tasks SET is_milestone = 1 WHERE duration_minutes = 0;
         UPDATE meta SET value = '1' WHERE key = 'format_version';
         PRAGMA user_version = 1;",
    )
    .expect("downgrade to format 1");
    let calendar = project.calendar_id.to_string();
    conn.execute(
        "INSERT INTO calendar_exceptions (id, calendar_id, name, start_date, end_date, is_working)
         VALUES ('00000000-0000-0000-0000-00000000aaaa', ?1, 'Saturday shift', '2027-03-06', '2027-03-06', 1)",
        [&calendar],
    )
    .expect("working row");
    conn.execute(
        "INSERT INTO calendar_exception_times (exception_id, start_minute, end_minute)
         VALUES ('00000000-0000-0000-0000-00000000aaaa', 480, 720)",
        [],
    )
    .expect("working time");
}

/// A format-1 file opens upgraded: `upgraded_from == Some(1)` (the file on
/// disk still says format 1), writable. Its holiday stays a holiday, the working row becomes an
/// exception (Saturday 08:00–12:00), and the "Shed finished" milestone has
/// `milestone == false` (reset) but is still a milestone by its zero
/// duration. The user's file on disk is not changed by opening.
///
/// Why it matters: users open M0 files in M1. The upgrade must be lossless
/// and must not invent "mark as milestone" flags the user never set.
#[test]
fn format_1_file_is_upgraded_on_open() {
    let mut project = shed();
    project.calendars[0].holidays.insert(date("2027-03-05"));
    let dir = temp_dir();
    let path = path_in(&dir, "old.gtra");
    write_format_1_file(&path, &project);
    let bytes_before = std::fs::read(&path).expect("read");

    let opened = open_ok(&path);
    assert_eq!(opened.upgraded_from, Some(1));
    // `format_version` reports the version of the file *on disk* (1); only
    // the working copy was upgraded to the current version.
    assert_eq!(opened.format_version, 1);
    assert_eq!(opened.access, gtra::Access::ReadWrite);
    let calendar = &opened.project.calendars[0];
    assert!(calendar.holidays.contains(&date("2027-03-05")));
    assert_eq!(calendar.exceptions.len(), 1);
    assert_eq!(calendar.exceptions[0].name, "Saturday shift");
    assert_eq!(calendar.exceptions[0].start, date("2027-03-06"));
    assert_eq!(
        calendar.exceptions[0].working_times,
        vec![WorkingTime::hours(8, 12)]
    );
    let finished = &opened.project.tasks[7];
    assert!(
        !finished.milestone,
        "is_milestone is reset by migration 0002"
    );
    assert!(finished.is_milestone(), "still a milestone by duration");
    assert_eq!(std::fs::read(&path).expect("read"), bytes_before);
}

/// In a session, the upgraded file reports `Compatibility::Upgraded { from:
/// 1, to: CURRENT_FORMAT_VERSION }` (notice code `gtra.upgraded`); after
/// Save the file on disk has the current format and opens without an
/// upgrade.
///
/// Why it matters: the UI shows "this file was upgraded" once, and the
/// upgrade only reaches the disk when the user saves.
#[test]
fn upgraded_session_saves_format_2() {
    let mut project = shed();
    project.calendars[0].holidays.insert(date("2027-03-05"));
    let dir = temp_dir();
    let path = path_in(&dir, "old.gtra");
    write_format_1_file(&path, &project);

    let (mut session, opened) =
        ProjectSession::open(&path, dir.path().join("working")).expect("open session");
    assert_eq!(session.upgraded_from(), Some(1));
    let compat = session.compatibility().expect("compat");
    assert_eq!(
        compat,
        Compatibility::Upgraded {
            from: 1,
            to: CURRENT_FORMAT_VERSION
        }
    );
    assert_eq!(compat.notice_code(), Some("gtra.upgraded"));
    session.save(&opened.project, &options()).expect("save");
    session.close(None).expect("close");

    let again = open_ok(&path);
    assert_eq!(again.upgraded_from, None);
    assert_eq!(again.format_version, CURRENT_FORMAT_VERSION);
    assert_eq!(again.project, opened.project);
}

/// Links to a summary task and the summary's subtasks survive a round trip
/// (the outline and the links are both stored).
///
/// Why it matters: M1 allows links into and out of summaries.
#[test]
fn links_to_summary_tasks_round_trip() {
    let mut project = shed();
    project.tasks[1].outline_level = 2;
    project.tasks[2].outline_level = 2;
    // Row 1 is now the summary of rows 2 and 3; remove links that would be
    // summary-to-own-subtask (1 -> 2, 1 -> 3) and link the summary to 4.
    let one = row_id(&project, 1);
    project.dependencies.retain(|d| d.predecessor != one);
    let four = row_id(&project, 4);
    link(&mut project, one, four);
    let dir = temp_dir();
    let path = path_in(&dir, "summary.gtra");
    save_ok(&path, &project);
    assert_eq!(normalized(&open_ok(&path).project), normalized(&project));
}
